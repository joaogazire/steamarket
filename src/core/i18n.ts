/** Idioma salvo → idioma válido; sem um salvo válido, a língua do navegador (en/es); senão português. */
export function lerIdioma(salvo: unknown, navegador: string | undefined): Idioma {
  if (salvo === "pt" || salvo === "en" || salvo === "es") return salvo;
  const base = (navegador ?? "").toLowerCase().split("-")[0];
  return base === "en" || base === "es" ? base : "pt";
}
